import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { parse } from 'smol-toml'
import { apps } from './apps.ts'
import { config } from './config.ts'
import { formatTableArray, getTableArray, replaceTable, type TomlTable } from './toml.ts'
import { initialMonitor, workspaceKeys, workspaceLabel, workspaceName, type WorkspaceKey } from './workspaces.ts'

// Generates two arrays in OmniWM's settings.toml and leaves every other setting alone:
// - [[workspaces]]: one per workspace key (see workspaces.ts)
// - [[appRules]]: one assignToWorkspace rule per bundle ID in apps.json. OmniWM applies
//   it only while the app has no windows, so an app's first window lands on its
//   workspace and later ones open on the active workspace.
// Settings that OmniWM's Settings window stores in these entries survive the build: a
// workspace keeps its id, layout and home monitor, and app rules the build didn't
// generate are kept as they are.

// Deterministic UUIDs keep generated entries stable across builds and machines.
function stableUUID(seed: string): string {
  const hash = createHash('sha1').update(`dots/omniwm/${seed}`).digest()
  hash[6] = (hash[6]! & 0x0f) | 0x50 // version 5 (name-based, SHA-1)
  hash[8] = (hash[8]! & 0x3f) | 0x80 // RFC 4122 variant
  const hex = hash.subarray(0, 16).toString('hex').toUpperCase()
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

// The build recognises the app rules it generated by this id.
function appRuleId(bundleId: string): string {
  return stableUUID(`app-rule/${bundleId}`)
}

function generateWorkspaces(existing: TomlTable[]): TomlTable[] {
  return workspaceKeys.map((key) => {
    const displayName = workspaceLabel(key)
    const previous = existing.find((workspace) => workspace.displayName === displayName)
    return {
      ...previous,
      id: previous?.id ?? stableUUID(`workspace/${key}`),
      name: workspaceName(key),
      displayName,
      layoutType: previous?.layoutType ?? 'default',
      monitorAssignment: previous?.monitorAssignment ?? { type: initialMonitor(key) },
    }
  })
}

function generateAppRules(existing: TomlTable[]): TomlTable[] {
  const manualRules = existing.filter((rule) => rule.id !== appRuleId(String(rule.bundleId)))
  const generatedRules = Object.entries(apps).flatMap(([key, bundleIds]) =>
    bundleIds.map((bundleId) => ({
      assignToWorkspace: workspaceName(key as WorkspaceKey),
      bundleId,
      id: appRuleId(bundleId),
    })),
  )
  return [...manualRules, ...generatedRules]
}

export function updateOmniWMSettings(): void {
  const path = config.omniwmSettings
  if (!existsSync(path)) {
    console.warn(`⚠️ ${path} not found, skipping OmniWM workspaces and app rules.`)
    return
  }

  const text = readFileSync(path, 'utf-8')
  let updated: string
  try {
    const settings = parse(text, { integersAsBigInt: true })
    const workspaces = generateWorkspaces(getTableArray(settings, 'workspaces'))
    const appRules = generateAppRules(getTableArray(settings, 'appRules'))
    updated = replaceTable(text, 'appRules', formatTableArray('appRules', appRules))
    updated = replaceTable(updated, 'workspaces', formatTableArray('workspaces', workspaces))
  } catch (error) {
    throw new Error(`${path}: ${(error as Error).message}`, { cause: error })
  }

  // Every write makes OmniWM reload, which drops runtime workspace-to-monitor moves.
  if (updated === text) {
    console.log(`✓ OmniWM settings unchanged.`)
    return
  }
  writeFileSync(path, updated, 'utf-8')
  console.log(`✓ OmniWM settings updated.`)
}
